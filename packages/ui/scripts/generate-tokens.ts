/**
 * Writes `src/tokens/tokens.gen.ts` from `design/system/tokens.json` (ADR
 * 0020, section 5): the token names as literal-union types and their values.
 * Run it after the design export changes: `bun run --filter @bd/ui tokens`.
 * `generate-tokens.test.ts` fails when the committed file differs.
 */
import { join } from "node:path";

export const SOURCE = join(import.meta.dir, "../../../design/system/tokens.json");
export const TARGET = join(import.meta.dir, "../src/tokens/tokens.gen.ts");
const BIOME = join(import.meta.dir, "../../../node_modules/.bin/biome");

interface Themed {
  light: string;
  dark: string;
}

/** The parts of the design tool's export this reads; other fields are ignored. */
export interface DesignTokens {
  color: { tokens: readonly { name: string; value: Themed }[] };
  shadow: { tokens: readonly { name: string; value: Themed }[] };
  type: {
    families: Readonly<Record<string, string>>;
    groups: readonly {
      family: string;
      styles: readonly {
        name: string;
        fontSize: string;
        lineHeight: number;
        fontWeight: number;
        fontStyle?: string;
        letterSpacing?: string;
      }[];
    }[];
  };
  spacing: { tokens: readonly { name: string; value: string }[] };
  radius: { tokens: readonly { name: string; value: string }[] };
  rule: { tokens: readonly { name: string; value: string }[] };
}

const str = (value: string | number) => JSON.stringify(value);
const union = (name: string, names: readonly string[]) =>
  `export type ${name} = ${names.map(str).join(" | ")};`;
/** `export const NAME: { readonly [K in KEY]: VALUE } = { ... };` */
const table = (name: string, key: string, value: string, entries: [string, string][]) =>
  `export const ${name}: { readonly [K in ${key}]: ${value} } = ` +
  `{${entries.map(([k, v]) => `${str(k)}: ${v}`).join(", ")}};`;

/** The file's text before formatting. */
function source(t: DesignTokens): string {
  const themed = (v: Themed) => `{ light: ${str(v.light)}, dark: ${str(v.dark)} }`;
  const styles = t.type.groups.flatMap((g) => g.styles.map((s) => ({ ...s, family: g.family })));
  const plain = (tokens: readonly { name: string; value: string }[]) =>
    tokens.map((x): [string, string] => [x.name, str(x.value)]);
  const style = (s: (typeof styles)[number]) => {
    const fields = [
      `family: ${str(s.family)}`,
      `fontSize: ${str(s.fontSize)}`,
      `lineHeight: ${s.lineHeight}`,
      `fontWeight: ${s.fontWeight}`,
    ];
    if (s.fontStyle !== undefined) fields.push(`fontStyle: ${str(s.fontStyle)}`);
    if (s.letterSpacing !== undefined) fields.push(`letterSpacing: ${str(s.letterSpacing)}`);
    return `{ ${fields.join(", ")} }`;
  };
  return [
    "// Generated by packages/ui/scripts/generate-tokens.ts from design/system/tokens.json.",
    "// Do not edit: change the design export and run `bun run --filter @bd/ui tokens`.",
    "",
    union(
      "ColorToken",
      t.color.tokens.map((x) => x.name),
    ),
    union(
      "ShadowToken",
      t.shadow.tokens.map((x) => x.name),
    ),
    union("FontFamily", Object.keys(t.type.families)),
    union(
      "TypeStyle",
      styles.map((s) => s.name),
    ),
    union(
      "SpaceToken",
      t.spacing.tokens.map((x) => x.name),
    ),
    union(
      "RadiusToken",
      t.radius.tokens.map((x) => x.name),
    ),
    union(
      "RuleToken",
      t.rule.tokens.map((x) => x.name),
    ),
    "",
    "/** A value in each theme. */",
    "export interface Themed { readonly light: string; readonly dark: string }",
    "",
    "/** One type style as the design states it. */",
    "export interface TypeToken {",
    "  readonly family: FontFamily;",
    "  readonly fontSize: string;",
    "  readonly lineHeight: number;",
    "  readonly fontWeight: number;",
    "  readonly fontStyle?: string;",
    "  readonly letterSpacing?: string;",
    "}",
    "",
    table(
      "COLORS",
      "ColorToken",
      "Themed",
      t.color.tokens.map((x) => [x.name, themed(x.value)]),
    ),
    table(
      "SHADOWS",
      "ShadowToken",
      "Themed",
      t.shadow.tokens.map((x) => [x.name, themed(x.value)]),
    ),
    table(
      "FAMILIES",
      "FontFamily",
      "string",
      Object.entries(t.type.families).map(([k, v]) => [k, str(v)]),
    ),
    "/** In the design's order: the order of the CSS variables and classes. */",
    table(
      "TYPE_STYLES",
      "TypeStyle",
      "TypeToken",
      styles.map((s) => [s.name, style(s)]),
    ),
    table("SPACING", "SpaceToken", "string", plain(t.spacing.tokens)),
    table("RADII", "RadiusToken", "string", plain(t.radius.tokens)),
    table("RULES", "RuleToken", "string", plain(t.rule.tokens)),
    "",
  ].join("\n");
}

/** The file's text, formatted as `bun run format` would leave it. */
export function generateTokens(tokens: DesignTokens): string {
  const run = Bun.spawnSync([BIOME, "format", `--stdin-file-path=${TARGET}`], {
    stdin: new TextEncoder().encode(source(tokens)),
  });
  if (run.exitCode !== 0) throw new Error(`biome format failed: ${run.stderr.toString()}`);
  return run.stdout.toString();
}

if (import.meta.main) {
  const tokens = (await Bun.file(SOURCE).json()) as DesignTokens;
  await Bun.write(TARGET, generateTokens(tokens));
  console.log(`wrote ${TARGET}`);
}
