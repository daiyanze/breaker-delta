import { describe, expect, test } from "bun:test";
import { TWO_COLUMNS_FROM } from "../tokens/index.ts";
import { COLORS, SHADOWS, TYPE_STYLES } from "../tokens/tokens.gen.ts";
import { bandColumns, fontLoading, smallType, tabularFigures } from "./checks.ts";
import { cssRules, cssValue, normalize, parseCss } from "./css.ts";
import { CSS_FILES, LAYERS, uiCss } from "./index.ts";

const css = uiCss();
const sheet = parseCss(css);
const rules = cssRules(sheet);
const src = `${import.meta.dir}/..`;

describe("uiCss() joins every .css file", () => {
  test("every .css file under src is in CSS_FILES, and nothing else", () => {
    const onDisk = [...new Bun.Glob("**/*.css").scanSync(src)].sort();
    expect(CSS_FILES.map((f) => f.path).sort()).toEqual(onDisk);
  });

  test("a .css file that is not in the list is reported", () => {
    const listed = new Set(CSS_FILES.map((f) => f.path));
    const missing = (paths: string[]) => paths.filter((p) => !listed.has(p));
    expect(missing([...CSS_FILES.map((f) => f.path), "patterns/Masthead/Masthead.css"])).toEqual([
      "patterns/Masthead/Masthead.css",
    ]);
  });

  test("each file is its text as on disk, written inside the layer it is listed in", async () => {
    for (const f of CSS_FILES) {
      expect(f.text).toBe(await Bun.file(`${src}/${f.path}`).text());
      const blocks = parseCss(f.text).children;
      expect(blocks.map((b) => b.prelude)).toEqual([`@layer ${f.layer}`]);
      expect(css).toContain(f.text.trim());
    }
  });
});

describe("the layers", () => {
  test("declared first, in the order tokens, base, primitives, patterns", () => {
    expect(LAYERS).toEqual(["tokens", "base", "primitives", "patterns"]);
    const [first] = sheet.children;
    expect(first?.statement).toBe(true);
    expect(first?.prelude).toBe("@layer tokens, base, primitives, patterns");
    expect(sheet.children.filter((b) => b.prelude.startsWith("@layer")).length).toBeGreaterThan(1);
  });

  test("the layer blocks come in that order, and every rule but @font-face is in one", () => {
    const order = sheet.children
      .filter((b) => !b.statement && b.prelude.startsWith("@layer "))
      .map((b) => LAYERS.indexOf(b.prelude.slice(7) as (typeof LAYERS)[number]));
    expect(order.every((n) => n >= 0)).toBe(true);
    expect(order).toEqual([...order].sort((a, b) => a - b));
    const outside = rules.filter((r) => r.layer === null).map((r) => r.selector);
    expect(new Set(outside)).toEqual(new Set(["@font-face"]));
  });
});

describe("themes (tokens layer)", () => {
  const theme = (selector: string, media: string[] = []) =>
    rules.filter(
      (r) => r.layer === "tokens" && r.selector === selector && r.media.join() === media.join(),
    );
  const declared = (name: string) =>
    rules.flatMap((r) => r.declarations.filter(([p]) => p === `--${name}`).map(([, v]) => v));

  test("each themed colour is one light-dark() declaration; one the same in both is plain", () => {
    for (const [name, themed] of Object.entries(COLORS)) {
      const t = { name, value: themed };
      const want =
        t.value.light === t.value.dark
          ? t.value.light
          : normalize(`light-dark(${t.value.light}, ${t.value.dark})`);
      expect({ name: t.name, values: declared(t.name) }).toEqual({ name: t.name, values: [want] });
    }
  });

  test("each shadow is in all three theme blocks: the root, dark from the system, dark by choice", () => {
    const [root] = theme(":root");
    const [system] = theme(':root:not([data-theme="light"])', ["(prefers-color-scheme: dark)"]);
    const [chosen] = theme(':root[data-theme="dark"]');
    for (const [name, themed] of Object.entries(SHADOWS)) {
      const property = `--${name}`;
      expect(root && cssValue(root, property)).toBe(normalize(themed.light));
      expect(system && cssValue(system, property)).toBe(normalize(themed.dark));
      expect(chosen && cssValue(chosen, property)).toBe(normalize(themed.dark));
      expect(declared(name)).toHaveLength(3);
    }
  });

  test("the system picks the theme unless data-theme does", () => {
    const [root] = theme(":root");
    const [light] = theme(':root[data-theme="light"]');
    const [dark] = theme(':root[data-theme="dark"]');
    expect(root && cssValue(root, "color-scheme")).toBe("light dark");
    expect(light && cssValue(light, "color-scheme")).toBe("light");
    expect(dark && cssValue(dark, "color-scheme")).toBe("dark");
  });

  test("the .type-<name> classes are generated by the tokens layer and sit in base", () => {
    const names = Object.keys(TYPE_STYLES);
    const classes = rules.filter((r) => r.selector.startsWith(".type-"));
    expect(classes.map((r) => r.selector)).toEqual(names.map((n) => `.type-${n}`));
    expect(classes.every((r) => r.layer === "base")).toBe(true);
  });
});

