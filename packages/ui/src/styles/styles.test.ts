import { describe, expect, test } from "bun:test";
import { TWO_COLUMNS_FROM } from "../tokens/index.ts";
import { COLORS, SHADOWS, TYPE_STYLES } from "../tokens/tokens.gen.ts";
import { bandColumns, fontLoading, smallType, tabularFigures } from "./checks.ts";
import { cssRules, cssValue, normalize, parseCss } from "./css.ts";
import { CSS_FILES, LAYERS, uiCss } from "./index.ts";

const css = uiCss();
const sheet = parseCss(css);
const rules = cssRules(sheet);
const src = `${import.meta.dir}/..`;

describe("uiCss() joins every .css file", () => {
  test("every .css file under src is in CSS_FILES, and nothing else", () => {
    const onDisk = [...new Bun.Glob("**/*.css").scanSync(src)].sort();
    expect(CSS_FILES.map((f) => f.path).sort()).toEqual(onDisk);
  });

  test("a .css file that is not in the list is reported", () => {
    const listed = new Set(CSS_FILES.map((f) => f.path));
    const missing = (paths: string[]) => paths.filter((p) => !listed.has(p));
    expect(missing([...CSS_FILES.map((f) => f.path), "patterns/Masthead/Masthead.css"])).toEqual([
      "patterns/Masthead/Masthead.css",
    ]);
  });

  test("each file is its text as on disk, written inside the layer it is listed in", async () => {
    for (const f of CSS_FILES) {
      expect(f.text).toBe(await Bun.file(`${src}/${f.path}`).text());
      const blocks = parseCss(f.text).children;
      expect(blocks.map((b) => b.prelude)).toEqual([`@layer ${f.layer}`]);
      expect(css).toContain(f.text.trim());
    }
  });
});

describe("the layers", () => {
  test("declared first, in the order tokens, base, primitives, patterns", () => {
    expect(LAYERS).toEqual(["tokens", "base", "primitives", "patterns"]);
    const [first] = sheet.children;
    expect(first?.statement).toBe(true);
    expect(first?.prelude).toBe("@layer tokens, base, primitives, patterns");
    expect(sheet.children.filter((b) => b.prelude.startsWith("@layer")).length).toBeGreaterThan(1);
  });

  test("the layer blocks come in that order, and every rule but @font-face is in one", () => {
    const order = sheet.children
      .filter((b) => !b.statement && b.prelude.startsWith("@layer "))
      .map((b) => LAYERS.indexOf(b.prelude.slice(7) as (typeof LAYERS)[number]));
    expect(order.every((n) => n >= 0)).toBe(true);
    expect(order).toEqual([...order].sort((a, b) => a - b));
    const outside = rules.filter((r) => r.layer === null).map((r) => r.selector);
    expect(new Set(outside)).toEqual(new Set(["@font-face"]));
  });
});

describe("themes (tokens layer)", () => {
  const theme = (selector: string, media: string[] = []) =>
    rules.filter(
      (r) => r.layer === "tokens" && r.selector === selector && r.media.join() === media.join(),
    );
  const declared = (name: string) =>
    rules.flatMap((r) => r.declarations.filter(([p]) => p === `--${name}`).map(([, v]) => v));

  test("each themed colour is one light-dark() declaration; one the same in both is plain", () => {
    for (const [name, themed] of Object.entries(COLORS)) {
      const t = { name, value: themed };
      const want =
        t.value.light === t.value.dark
          ? t.value.light
          : normalize(`light-dark(${t.value.light}, ${t.value.dark})`);
      expect({ name: t.name, values: declared(t.name) }).toEqual({ name: t.name, values: [want] });
    }
  });

  test("each shadow is in all three theme blocks: the root, dark from the system, dark by choice", () => {
    const [root] = theme(":root");
    const [system] = theme(':root:not([data-theme="light"])', ["(prefers-color-scheme: dark)"]);
    const [chosen] = theme(':root[data-theme="dark"]');
    for (const [name, themed] of Object.entries(SHADOWS)) {
      const property = `--${name}`;
      expect(root && cssValue(root, property)).toBe(normalize(themed.light));
      expect(system && cssValue(system, property)).toBe(normalize(themed.dark));
      expect(chosen && cssValue(chosen, property)).toBe(normalize(themed.dark));
      expect(declared(name)).toHaveLength(3);
    }
  });

  test("the system picks the theme unless data-theme does", () => {
    const [root] = theme(":root");
    const [light] = theme(':root[data-theme="light"]');
    const [dark] = theme(':root[data-theme="dark"]');
    expect(root && cssValue(root, "color-scheme")).toBe("light dark");
    expect(light && cssValue(light, "color-scheme")).toBe("light");
    expect(dark && cssValue(dark, "color-scheme")).toBe("dark");
  });

  test("the .type-<name> classes are generated by the tokens layer and sit in base", () => {
    const names = Object.keys(TYPE_STYLES);
    const classes = rules.filter((r) => r.selector.startsWith(".type-"));
    expect(classes.map((r) => r.selector)).toEqual(names.map((n) => `.type-${n}`));
    expect(classes.every((r) => r.layer === "base")).toBe(true);
  });
});

// The design system's four rules, each read from the rules and each shown
// to report a planted violation.
describe("tabular figures", () => {
  test("the stylesheet keeps them", () => {
    expect(tabularFigures(css)).toEqual([]);
  });

  test("a figure style without tabular numbers is reported", () => {
    const planted = `${css}\n@layer patterns { .wave-number { font-variant-numeric: proportional-nums; } }`;
    expect(tabularFigures(planted)).toEqual([
      ".wave-number sets font-variant-numeric: proportional-nums",
    ]);
    expect(tabularFigures(`${css}\n.x { font: 17px serif; }`)).toEqual([
      ".x sets font: 17px serif, which resets the figures",
    ]);
    const noRoot = css.replace("font-variant-numeric: tabular-nums;", "");
    expect(tabularFigures(noRoot)).toEqual([
      "html does not set font-variant-numeric: tabular-nums",
    ]);
  });
});

describe("no type under 13px", () => {
  test("the stylesheet has none", () => {
    expect(smallType(css)).toEqual([]);
    const sizes = rules.flatMap((r) =>
      r.declarations
        .filter(([p]) => /^--type-.*-size$/.test(p))
        .map(([, v]) => Number.parseFloat(v)),
    );
    expect(Math.min(...sizes)).toBe(13);
  });

  test("a 12px size is reported, as a property and as a type variable", () => {
    expect(smallType(`${css}\n@layer base { small { font-size: 12px; } }`)).toEqual([
      "small font-size: 12px is under 13px",
    ]);
    expect(smallType(`${css}\n:root { --type-tiny-size: 12px; }`)).toEqual([
      ":root --type-tiny-size: 12px is under 13px",
    ]);
  });
});

describe("fonts", () => {
  test("one optional @font-face per file at /fonts, outside the layers", () => {
    const preloads = ["fraunces-latin", "fraunces-italic-latin", "instrument-sans-latin"].map(
      (f) => `/fonts/${f}.woff2`,
    );
    expect(fontLoading(css, preloads)).toEqual([]);
    expect(css).not.toContain("fonts.googleapis.com");
  });

  test("a face that can swap in late is reported", () => {
    const swap = css.replace("font-display:optional", "font-display:swap");
    expect(fontLoading(swap, []).filter((p) => p.includes("swap in late"))).toHaveLength(1);
  });
  // The page head's preloads, and a missing one: `apps/web/src/local/head.test.ts`.
});

describe("the band: one column on phones, two from the breakpoint", () => {
  test("the stylesheet has both", () => {
    expect(bandColumns(css)).toEqual([]);
  });

  test("a band column rule removed is reported", () => {
    const band = CSS_FILES.find((f) => f.path === "patterns/Band/Band.css")?.text ?? "";
    const two = "grid-template-columns: minmax(0, var(--rail)) minmax(0, 1fr);";
    expect(band).toContain(two);
    expect(bandColumns(css.replace(two, ""))).toEqual([
      `.band from ${TWO_COLUMNS_FROM}: grid-template-columns is unset, not minmax(0, var(--rail)) minmax(0, 1fr)`,
    ]);
    const one = "grid-template-columns: minmax(0, 1fr);";
    expect(bandColumns(css.replace(one, ""))).toEqual([
      ".band: grid-template-columns is unset, not minmax(0, 1fr)",
    ]);
  });

  test("a breakpoint other than TWO_COLUMNS_FROM is reported", () => {
    const other = css.replaceAll(`(min-width: ${TWO_COLUMNS_FROM})`, "(min-width: 900px)");
    expect(bandColumns(other).some((p) => p.includes("(min-width: 900px)"))).toBe(true);
  });
});

describe("page width and band spacing (moved from apps/web layout.test.ts)", () => {
  const at = (selector: string, wide: boolean) =>
    rules.find(
      (r) =>
        r.selector === selector &&
        (wide ? r.media.join() === `(min-width: ${TWO_COLUMNS_FROM})` : r.media.length === 0) &&
        r.layer !== "tokens",
    ) ?? { declarations: [] };

  test("the page is at most `content` wide with the side margins outside it", () => {
    const page = at(".page", false);
    expect(cssValue(page, "box-sizing")).toBe("content-box");
    expect(cssValue(page, "max-width")).toBe("var(--content)");
    expect(cssValue(page, "padding-inline")).toBe("var(--page-gutter)");
  });

  test("phones get the phone values, wide screens the desktop ones", () => {
    const vars = (wide: boolean) =>
      Object.fromEntries(
        rules
          .filter(
            (r) =>
              r.selector === ":root" &&
              r.layer !== "tokens" &&
              (wide ? r.media.length === 1 : r.media.length === 0),
          )
          .flatMap((r) => r.declarations),
      );
    expect(vars(false)).toEqual({
      "--page-gutter": "var(--phone-gutter)",
      "--band-space": "var(--space-7)",
      "--band-name-size": "var(--phone-section-size)",
    });
    expect(vars(true)).toEqual({
      "--page-gutter": "var(--space-6)",
      "--band-space": "var(--space-8)",
      "--band-name-size": "var(--type-section-size)",
    });
  });

  test("bands are separated by a thin ink rule and the band spacing", () => {
    const band = at(".band", false);
    expect(cssValue(band, "border-top")).toBe("var(--rule-thin) solid var(--ink)");
    expect(cssValue(band, "padding-block")).toBe("var(--band-space)");
    expect(cssValue(at(".band", true), "column-gap")).toBe("var(--space-8)");
  });

  test("no layout rule sets a fixed width that could overflow a phone", () => {
    for (const sel of [".page", ".band", ".band-rail", ".band-body", ".band-name"]) {
      for (const r of rules.filter((x) => x.selector === sel)) {
        for (const [p, v] of r.declarations) {
          if (/^(min-)?width$/.test(p)) expect({ sel, p, v }).toEqual({ sel, p, v: "0" });
        }
      }
    }
  });
});

describe("the CSS reader", () => {
  test("reads statements, nesting with &, media inside a rule, comments and strings", () => {
    const read = cssRules(
      parseCss(
        '@layer a, b;\n/* x { } */\n@layer a { .p { color: var(--x); & > .q { content: "{;}"; } @media (min-width: 1px) { gap: 0; } } }',
      ),
    );
    expect(read.map((r) => [r.layer, r.media.join(), r.selector])).toEqual([
      ["a", "", ".p"],
      ["a", "", ".p > .q"],
      ["a", "(min-width: 1px)", ".p"],
    ]);
    expect(read[1]?.declarations).toEqual([["content", '"{;}"']]);
  });

  test("text it cannot close throws", () => {
    expect(() => parseCss(".a { gap: 0;")).toThrow("not closed");
    expect(() => parseCss(".a { } }")).toThrow("closes nothing");
    expect(() => parseCss('.a { content: "x }')).toThrow("not closed");
  });
});
