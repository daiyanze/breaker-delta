describe("tabular figures", () => {
  test("the stylesheet keeps them", () => {
    expect(tabularFigures(css)).toEqual([]);
  });

  test("a figure style without tabular numbers is reported", () => {
    const planted = `${css}\n@layer patterns { .wave-number { font-variant-numeric: proportional-nums; } }`;
    expect(tabularFigures(planted)).toEqual([
      ".wave-number sets font-variant-numeric: proportional-nums",
    ]);
    expect(tabularFigures(`${css}\n.x { font: 17px serif; }`)).toEqual([
      ".x sets font: 17px serif, which resets the figures",
    ]);
    const noRoot = css.replace("font-variant-numeric: tabular-nums;", "");
    expect(tabularFigures(noRoot)).toEqual([
      "html does not set font-variant-numeric: tabular-nums",
    ]);
  });
});

describe("no type under 13px", () => {
  test("the stylesheet has none", () => {
    expect(smallType(css)).toEqual([]);
    const sizes = rules.flatMap((r) =>
      r.declarations
        .filter(([p]) => /^--type-.*-size$/.test(p))
        .map(([, v]) => Number.parseFloat(v)),
    );
    expect(Math.min(...sizes)).toBe(13);
  });

  test("a 12px size is reported, as a property and as a type variable", () => {
    expect(smallType(`${css}\n@layer base { small { font-size: 12px; } }`)).toEqual([
      "small font-size: 12px is under 13px",
    ]);
    expect(smallType(`${css}\n:root { --type-tiny-size: 12px; }`)).toEqual([
      ":root --type-tiny-size: 12px is under 13px",
    ]);
  });
});

