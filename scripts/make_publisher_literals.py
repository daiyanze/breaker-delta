#!/usr/bin/env python3
"""Generate packages/publisher/src/literals.ts from radar/publish.py.

The publisher's big literal tables (STRINGS in three languages, ABOUT,
CSS, HOOK_T / tips, share platforms/icons, source domains, slot/level
maps) must match the Python original byte-for-byte, so they are not
transcribed by hand: this script imports radar.publish and re-emits
the values as JSON (valid TS expressions) with type annotations.
Re-run after any change to those tables in publish.py:

    python3 scripts/make_publisher_literals.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from radar import publish  # noqa: E402
OUT = ROOT / "packages" / "publisher" / "src" / "literals.ts"

# (export name, publish.py attribute, TS type)
TABLES = [
    ("CSS", "CSS", "string"),
    ("STRINGS", "STRINGS", "Record<string, Record<string, string | string[]>>"),
    ("ABOUT", "ABOUT", "Record<string, string>"),
    ("SOURCE_DOMAINS", "SOURCE_DOMAINS", "Record<string, string>"),
    ("HOOK_T", "HOOK_T", "Record<string, Record<string, string>>"),
    ("SHORT_TIPS", "SHORT_TIPS", "Record<string, string[]>"),
    ("LONG_TIPS", "LONG_TIPS", "Record<string, string[]>"),
    ("LEVEL_I18N", "LEVEL_I18N", "Record<string, Record<string, string>>"),
    ("CAT_I18N", "CAT_I18N", "Record<string, Record<string, string>>"),
    ("CAT_KEYS", "CAT_KEYS", "Record<string, string>"),
    ("SRC_ALIASES", "SRC_ALIASES", "Record<string, string>"),
    ("OFFICIAL_HINTS", "OFFICIAL_HINTS", "string[]"),
    ("TECH_HINTS", "TECH_HINTS", "string[]"),
    ("SHARE_ICONS", "SHARE_ICONS", "Record<string, string>"),
    ("SHARE_PLATFORMS", "SHARE_PLATFORMS", "Record<string, [string, string]>"),
    ("SLOT", "SLOT", "Record<string, [string, number]>"),
    ("LEVELS", "LEVELS", "Record<string, [string, string]>"),
    ("HTML_LANG", "HTML_LANG", "Record<string, string>"),
    ("LANG_LABEL", "LANG_LABEL", "Record<string, string>"),
]


def main() -> None:
    parts = [
        "// GENERATED by scripts/make_publisher_literals.py from",
        "// radar/publish.py — do not edit by hand. The values are the",
        "// Python literals re-emitted as JSON so the three-language",
        "// string tables, CSS and copy stay byte-identical.",
        "",
    ]
    for name, attr, typ in TABLES:
        value = getattr(publish, attr)
        blob = json.dumps(value, ensure_ascii=False, indent=1)
        parts.append(f"export const {name}: {typ} = {blob};")
        parts.append("")
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
